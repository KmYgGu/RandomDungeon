using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class DungeonBlueprint : MonoBehaviour
{
    public Vector2Int mapSize = new Vector2Int(50, 50); // 전체 던전 크기

    [Header("방 개수")]
    public int minRoomCount = 5;
    public int maxRoomCount = 10;

    [Header("랜덤 도로 개수")]
    public int minExtraPathCount = 1;
    public int maxExtraPathCount = 4;

    [Header("구역 정의")]
    public List<SectionDefinition> sections = new List<SectionDefinition>();

    [Header("자동 기본 연결 생성 여부")]
    public bool autoGenerateDefaultConnections = true;

    [Header("기본 연결 정보")]
    public List<SectionConnection> defaultConnections = new List<SectionConnection>();
}

// 섹션 정의용 클래스
[System.Serializable]
public class SectionDefinition
{
    public int index;
    public Vector2Int topLeft;
    public Vector2Int size;

    [Header("방 제약")]
    public Vector2Int minRoomSize = new Vector2Int(3, 3);
    public Vector2Int maxRoomSize = new Vector2Int(8, 8);  // 새로 추가
    public bool forceNoRoom = false;
    [Range(0f, 1f)]
    public float roomWeight = 0.5f;
}

// 기본 연결 정의
// [Serializable] 이 없으면 Inspector 의 defaultConnections 리스트가 언제나 비어 있어,
// autoGenerateDefaultConnections 를 꺼도 수동 연결이 적용되지 않았다.
[System.Serializable]
public class SectionConnection
{
    public int fromSection;
    public int toSection;
}
