using System.Collections.Generic;
using UnityEngine;


public class DefaultConnectionPlanner : IConnectionPlanner
{
    private struct SectionPair
    {
        public int a;
        public int b;

        public SectionPair(int a, int b)
        {
            this.a = a;
            this.b = b;
        }
    }

    public List<SectionConnection> PlanConnections(
        DungeonBlueprint blueprint,
        List<Section> sections)
    {
        // 최종 반환 리스트 (명시적 new)
        List<SectionConnection> connections = new List<SectionConnection>();
        int sectionCount = sections.Count;

        if (sectionCount < 2)
            return connections;

        // 가능한 모든 섹션 쌍
        List<SectionPair> possiblePairs = new List<SectionPair>();
        for (int i = 0; i < sectionCount; i++)
        {
            for (int j = i + 1; j < sectionCount; j++)
            {
                possiblePairs.Add(new SectionPair(i, j));
            }
        }

        // 1. 수동 연결 우선
        if (!blueprint.autoGenerateDefaultConnections &&
            blueprint.defaultConnections != null &&
            blueprint.defaultConnections.Count > 0)
        {
            foreach (var def in blueprint.defaultConnections)
            {
                connections.Add(new SectionConnection
                {
                    fromSection = def.fromSection,
                    toSection = def.toSection
                });
            }
        }
        else
        {
            // 2. MST 기반 자동 연결
            UnionFind uf = new UnionFind(sectionCount);
            Shuffle(possiblePairs);

            foreach (var pair in possiblePairs)
            {
                if (uf.Find(pair.a) != uf.Find(pair.b))
                {
                    uf.Union(pair.a, pair.b);
                    connections.Add(new SectionConnection
                    {
                        fromSection = pair.a,
                        toSection = pair.b
                    });
                }

                if (connections.Count >= sectionCount - 1)
                    break;
            }
        }

        // 3. 추가 랜덤 연결
        AddExtraConnections(
            connections,
            blueprint.minExtraPathCount,
            blueprint.maxExtraPathCount,
            sectionCount
        );

        return connections;
    }

    private void AddExtraConnections(
        List<SectionConnection> connections,
        int minExtra,
        int maxExtra,
        int sectionCount)
    {
        int extraCount = Random.Range(minExtra, maxExtra + 1);
        HashSet<long> existing = new HashSet<long>();

        foreach (var c in connections)
        {
            existing.Add(MakeKey(c.fromSection, c.toSection));
            existing.Add(MakeKey(c.toSection, c.fromSection));
        }

        int attempts = 0;
        while (extraCount > 0 && attempts < sectionCount * sectionCount)
        {
            attempts++;

            int a = Random.Range(0, sectionCount);
            int b = Random.Range(0, sectionCount);
            if (a == b) continue;

            long key = MakeKey(a, b);
            if (existing.Contains(key))
                continue;

            connections.Add(new SectionConnection
            {
                fromSection = a,
                toSection = b
            });

            existing.Add(key);
            existing.Add(MakeKey(b, a));
            extraCount--;
        }
    }

    private long MakeKey(int a, int b)
    {
        return (((long)a) << 32) | (uint)b;
    }

    private void Shuffle(List<SectionPair> list)
    {
        for (int i = 0; i < list.Count; i++)
        {
            int r = Random.Range(i, list.Count);
            SectionPair temp = list[i];
            list[i] = list[r];
            list[r] = temp;
        }
    }

    private class UnionFind
    {
        private int[] parent;

        public UnionFind(int n)
        {
            parent = new int[n];
            for (int i = 0; i < n; i++)
                parent[i] = i;
        }

        public int Find(int x)
        {
            if (parent[x] != x)
                parent[x] = Find(parent[x]);
            return parent[x];
        }

        public void Union(int a, int b)
        {
            a = Find(a);
            b = Find(b);
            if (a != b)
                parent[b] = a;
        }
    }
}
