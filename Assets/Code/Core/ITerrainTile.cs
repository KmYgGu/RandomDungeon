/// <summary>
/// 타일 애셋이 스스로 "나는 어떤 땅인가" 를 답한다.
///
/// ── 왜 이름으로 가르지 않게 되었나 ────────────────────────────────
/// 예전에는 TileRules 가 타일 <b>이름</b>으로 지형을 갈랐다("S1Wall" 이면 벽).
/// 스테이지가 하나뿐일 때는 그럭저럭 돌았지만, 2스테이지 벽을 만들면
/// "S2Wall" 은 어느 목록에도 없어서 <b>걸어서 통과되는 벽</b>이 된다.
/// 에러는 나지 않는다. 아이템에서 이름을 신원으로 쓰다 겪은 것과 같은 일이다.
///
/// 이제 지형은 타일 애셋에 붙어 다닌다. 스테이지를 몇 개를 만들든 코드를
/// 고칠 일이 없고, 애셋에서 종류를 고르는 것을 잊으면 인스펙터에 보인다.
///
/// ── 겉모습과 규칙은 여전히 별개다 ─────────────────────────────────
/// 그림이 물이라고 해서 물의 규칙을 따를 이유가 없다. 맵 끝자락의 물
/// (S1BedrockWater)이 그 예다 — 물처럼 보이지만 Terrain 은 Wall 이다.
/// 물로 두면 물에 들어갈 수 있는 상태일 때 헤엄쳐 맵 밖으로 나가 버린다.
///
/// Unity 것을 하나도 건드리지 않으므로 Unity 없이 그대로 확인할 수 있다.
/// </summary>
public interface ITerrainTile
{
    /// <summary>이 타일이 만드는 땅의 종류.</summary>
    TileRules.TerrainKind Terrain { get; }

    /// <summary>
    /// 이 타일을 없앨 수 있는가.
    ///
    /// 맵 끝자락만 false 다. 벽을 허무는 수단(굴착 지팡이 같은 것)은 전부
    /// 이 판정을 거쳐야 한다 — 각자 "가장자리인가" 를 좌표로 따로 계산하면
    /// 맵 크기가 바뀌거나 수단이 하나 늘 때마다 어긋난다.
    /// </summary>
    bool Destructible { get; }
}
